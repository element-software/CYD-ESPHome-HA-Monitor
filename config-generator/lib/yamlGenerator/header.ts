function bannerName(friendlyName?: string, deviceName?: string): string {
  const raw = [friendlyName, deviceName].map((s) => s?.trim()).find(Boolean) || 'HAMon';
  return raw.replace(/[\r\n\u2028\u2029]+/g, ' ').trim() || 'HAMon';
}

export function generateHeader(friendlyName?: string, deviceName?: string): string {
  const name = bannerName(friendlyName, deviceName);
  return `# ==============================================================================
#  CYD 2.8" ${name} - Home Assistant Monitor
#  A customisable clock & sensor dashboard for the ESP32 Cheap Yellow Display
#
#  Generated by CYD HAMon Config Generator
#  https://github.com/element-software/CYD-ESPHome-HA-Monitor
#
#  License: MIT
# ==============================================================================
#
#  SUBSTITUTIONS - Customise your dashboard by editing the values below.
#  Passwords and keys should be stored in your secrets.yaml file.
#
# ==============================================================================
`;
}
