import { generateHeader } from '../header';
import { generateYaml } from '../index';
import { defaultConfig } from '@/lib/defaultConfig';

describe('generateHeader', () => {
  it('uses HAMon when no names are provided', () => {
    const header = generateHeader();
    expect(header).toContain('CYD 2.8" HAMon - Home Assistant Monitor');
    expect(header).toContain('Generated by CYD HAMon Config Generator');
  });

  it('uses friendly name in the banner and keeps HAMon in the generator attribution', () => {
    const header = generateHeader('glight', 'glight-device');
    expect(header).toContain('CYD 2.8" glight - Home Assistant Monitor');
    expect(header).toContain('Generated by CYD HAMon Config Generator');
  });

  it('keeps names with newlines inside the comment banner', () => {
    const header = generateHeader('Kitchen\nota:\n  password: x', 'dev');
    expect(header).toContain('CYD 2.8" Kitchen ota:   password: x - Home Assistant Monitor');
    expect(header).not.toMatch(/^ota:/m);
  });
});

describe('generateYaml header names', () => {
  it('embeds the configured friendly name', () => {
    const yaml = generateYaml({
      ...defaultConfig,
      deviceName: 'glight',
      friendlyName: 'GLight',
    });
    expect(yaml).toContain('CYD 2.8" GLight - Home Assistant Monitor');
  });
});
